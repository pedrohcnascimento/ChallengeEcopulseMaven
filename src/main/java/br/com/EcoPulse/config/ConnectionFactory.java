    private boolean autoInit;

    public ConnectionFactory() {
    }

    @PostConstruct
    public void init() {
        configure(configuredUrl, configuredUser, configuredPassword, configuredDriver);
        if (!autoInit) return;
        if (activeUrl.startsWith("jdbc:oracle:") && (activeUser == null || activeUser.isBlank())) {
            LOGGER.warn("Variáveis DB_USER/DB_PASSWORD não definidas; inicialização automática ignorada no boot.");
            return;
        }
        try {
            initializeDatabase();
        } catch (Exception ex) {
            LOGGER.warn("Aviso ao verificar schema T_SOUL_ no boot: {}", ex.getMessage());
        }
    }

    public static void configure(String url, String user, String password, String driver) {
        activeUrl = url;
        activeUser = user == null ? "" : user;
        activePassword = password == null ? "" : password;
        activeDriver = driver;
    }

    public static Connection getConnection() throws SQLException {
        Connection txConn = TRANSACTION_CONTEXT.get();
        if (txConn != null) {
            return txConn;
        }
        try {
            Class.forName(activeDriver);
            return DriverManager.getConnection(activeUrl, activeUser, activePassword);
        } catch (ClassNotFoundException exception) {
            throw new SQLException("Driver JDBC não está disponível no classpath: " + activeDriver, exception);
        }
    }

    public static <T> T executeInTransaction(Supplier<T> action) {
        if (TRANSACTION_CONTEXT.get() != null) {
            return action.get();
        }
        Connection rawConnection = null;
        try {
            Class.forName(activeDriver);
            rawConnection = DriverManager.getConnection(activeUrl, activeUser, activePassword);
            rawConnection.setAutoCommit(false);

            final Connection delegate = rawConnection;
            Connection nonClosingProxy = (Connection) Proxy.newProxyInstance(
                    Connection.class.getClassLoader(),
                    new Class<?>[]{Connection.class},
                    (proxy, method, args) -> {
                        if ("close".equals(method.getName())) return null;
                        if ("isClosed".equals(method.getName())) return delegate.isClosed();
                        return method.invoke(delegate, args);
                    });

            TRANSACTION_CONTEXT.set(nonClosingProxy);
            T result = action.get();
            rawConnection.commit();
            return result;
        } catch (RuntimeException ex) {
            rollbackQuietly(rawConnection);
            throw ex;
        } catch (Exception ex) {
            rollbackQuietly(rawConnection);
            throw new PersistenceException("Erro transacional no banco de dados", ex);
        } finally {
            TRANSACTION_CONTEXT.remove();
            closeQuietly(rawConnection);
        }
    }

    public static void executeInTransaction(Runnable action) {
        executeInTransaction(() -> {
            action.run();
            return null;
        });
    }

    public static void initializeDatabase() {
        try (Connection connection = getConnection()) {
            for (String ddl : DDL_STATEMENTS) {
                createTableIfAbsent(connection, ddl);
            }
        } catch (SQLException exception) {
            throw new PersistenceException("Não foi possível inicializar o banco de dados", exception);
        }
    }

    /** Remove todos os registros na ordem reversa das chaves estrangeiras, preservando as tabelas e o schema. */
    public static void clearData() {
        try (Connection connection = getConnection(); Statement statement = connection.createStatement()) {
            for (String table : TABLES_REVERSE_FK_ORDER) {
                if (tableExists(connection, table)) {
                    statement.executeUpdate("DELETE FROM " + table);
                }
            }
        } catch (SQLException exception) {
            throw new PersistenceException("Não foi possível limpar os registros do banco de dados", exception);
        }
    }

    private static void createTableIfAbsent(Connection connection, String ddl) throws SQLException {
        String normalized = ddl.trim();
        int start = "CREATE TABLE ".length();
        int space = normalized.indexOf(' ', start);
        int paren = normalized.indexOf('(', start);
        int nameEnd = (space > 0 && space < paren) ? space : paren;
        String tableName = normalized.substring(start, nameEnd).trim().toUpperCase();

        if (!tableExists(connection, tableName)) {
            try (Statement statement = connection.createStatement()) {
                statement.execute(normalized);
            } catch (SQLException ex) {
                if (ex.getErrorCode() != 955) {
                    throw ex;
                }
            }
        }
    }

    private static boolean tableExists(Connection connection, String tableName) throws SQLException {
        DatabaseMetaData metaData = connection.getMetaData();
        String schema = null;
        try {
            schema = connection.getSchema();
        } catch (SQLException ignored) {
        }
        try (ResultSet rs = metaData.getTables(null, schema, tableName.toUpperCase(), new String[]{"TABLE"})) {
            return rs.next();
        }
    }

    private static void rollbackQuietly(Connection connection) {
        if (connection != null) {
            try { connection.rollback(); } catch (SQLException ex) { LOGGER.error("Erro no rollback JDBC", ex); }
        }
    }

    private static void closeQuietly(Connection connection) {
        if (connection != null) {
            try { connection.setAutoCommit(true); } catch (SQLException ignored) { }
            try { connection.close(); } catch (SQLException ex) { LOGGER.error("Erro ao fechar conexão JDBC", ex); }
        }
    }

    private static String envOrDefault(String key, String defaultValue) {
        String val = System.getenv(key);
        return (val == null || val.isBlank()) ? defaultValue : val;
    }
